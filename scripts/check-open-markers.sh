#!/usr/bin/env bash
# Open markers: every TODO / CHANGEME / TO MEASURE / TO-VERIFY marker in tracked files under deploy, docs, src, tools,
# tests, evals and scripts must have a row in docs/spec/OPEN-MARKERS.md (file, line, text, owner).
#
#   scripts/check-open-markers.sh           check: fail if a marker has no row, or a row has no marker
#   scripts/check-open-markers.sh --write   regenerate the table; owners of existing rows are kept
#
# Owners: agent | human | hardware. New rows get a default from the marker (TO MEASURE -> hardware,
# TO-VERIFY and CHANGEME -> human, TODO -> agent); edit the owner in the table, the check does not compare owners.
# A row key is file + line number + text, so any edit that moves or rewrites a marker needs --write in the same PR.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

TABLE=docs/spec/OPEN-MARKERS.md
PATTERN='TODO|CHANGEME|TO MEASURE|TO-VERIFY'
SCAN_PATHS=(deploy docs src tools tests evals scripts)
# Excluded: the specification itself (it describes the markers) and the two check scripts (they contain the patterns).
EXCLUDES=(':!docs/spec' ':!scripts/check-open-markers.sh' ':!scripts/check-spec.sh')

write=false
case "${1:-}" in
  --write) write=true ;;
  "") ;;
  *) echo "usage: $0 [--write]" >&2; exit 2 ;;
esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Scan: one line per marker as file<TAB>line<TAB>text<TAB>owner. Text is trimmed, cut to 160 characters,
# with tabs and pipes made safe for the table.
git grep -n -I -E "$PATTERN" -- "${SCAN_PATHS[@]}" "${EXCLUDES[@]}" > "$tmp/raw" || true
: > "$tmp/scan"
while IFS= read -r raw; do
  file="${raw%%:*}"
  rest="${raw#*:}"
  line="${rest%%:*}"
  text="${rest#*:}"
  # Trim, cut to 160 characters, trim again (the cut can leave a trailing space), then escape pipes last.
  text="$(printf '%s' "$text" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/\t/ /g' | cut -c1-160 | sed -e 's/[[:space:]]*$//' -e 's/|/\\|/g')"
  case "$text" in
    *"TO MEASURE"*) owner=hardware ;;
    *TO-VERIFY*|*CHANGEME*) owner=human ;;
    *) owner=agent ;;
  esac
  printf '%s\t%s\t%s\t%s\n' "$file" "$line" "$text" "$owner" >> "$tmp/scan"
done < "$tmp/raw"
sort -t$'\t' -k1,1 -k2,2n "$tmp/scan" -o "$tmp/scan"

# Table rows currently in the file: the same four fields, read from lines of the form "| file | line | text | owner |".
# Escaped pipes (\|) inside text are protected before splitting on '|'.
: > "$tmp/table"
if [ -f "$TABLE" ]; then
  awk -v OFS='\t' '
    /^\| / && !/^\| File / {
      s = $0
      gsub(/\\\|/, "\001", s)
      n = split(s, a, "|")
      if (n >= 6) {
        gsub(/\001/, "\\|", a[4])
        gsub(/^ +| +$/, "", a[2]); gsub(/^ +| +$/, "", a[3]); gsub(/^ +| +$/, "", a[4]); gsub(/^ +| +$/, "", a[5])
        print a[2], a[3], a[4], a[5]
      }
    }' "$TABLE" | sort -t$'\t' -k1,1 -k2,2n > "$tmp/table"
fi

if [ "$write" = true ]; then
  {
    echo "# Open markers"
    echo
    echo "Generated by \`scripts/check-open-markers.sh --write\`. CI runs the check (workflow \`spec-check\`) and fails when a marker is not listed here or a row no longer matches a marker."
    echo "Owners: \`agent\` (an agent can close it), \`human\` (needs a person or an online source), \`hardware\` (needs the target machine). Set the owner by editing the row; \`--write\` keeps it."
    echo
    echo "| File | Line | Text | Owner |"
    echo "|---|---|---|---|"
    # Keep owners from the existing table where the key (file, line, text) still matches.
    # Select by file name, not by NR==FNR: an empty first file would otherwise swallow every line of the second.
    awk -F'\t' -v OFS='\t' -v table="$tmp/table" '
      FILENAME == table { owner[$1 SUBSEP $2 SUBSEP $3] = $4; next }
      {
        key = $1 SUBSEP $2 SUBSEP $3
        o = (key in owner) ? owner[key] : $4
        printf "| %s | %s | %s | %s |\n", $1, $2, $3, o
      }' "$tmp/table" "$tmp/scan"
  } > "$TABLE"
  echo "wrote $TABLE with $(wc -l < "$tmp/scan") marker(s)"
  exit 0
fi

# Check: compare keys (file, line, text). Owners are not compared.
cut -f1-3 "$tmp/scan" | sort > "$tmp/scan.keys"
cut -f1-3 "$tmp/table" | sort > "$tmp/table.keys"
missing="$(comm -23 "$tmp/scan.keys" "$tmp/table.keys")"
stale="$(comm -13 "$tmp/scan.keys" "$tmp/table.keys")"
status=0
if [ -n "$missing" ]; then
  echo "markers not in $TABLE (run scripts/check-open-markers.sh --write, then set the owner):" >&2
  printf '%s\n' "$missing" | sed 's/^/  /' >&2
  status=1
fi
if [ -n "$stale" ]; then
  echo "rows in $TABLE without a matching marker (run scripts/check-open-markers.sh --write):" >&2
  printf '%s\n' "$stale" | sed 's/^/  /' >&2
  status=1
fi
if [ "$status" -eq 0 ]; then
  echo "open markers: $(wc -l < "$tmp/scan") marker(s), all listed in $TABLE"
fi
exit "$status"
